/**
 * Hook share URL generation — captures the v.douyin.com link
 * without needing to tap the share button.
 */
import Java from 'frida-java-bridge';

function install() {
  if (!Java.available) { setTimeout(install, 500); return; }

  Java.perform(() => {
    // Hook ClipboardManager.setPrimaryClip — catches ALL clipboard writes
    try {
      const CM = Java.use('android.content.ClipboardManager');
      CM.setPrimaryClip.implementation = function (clip) {
        try {
          const item = clip.getItemAt(0);
          const text = item.getText();
          if (text) {
            const s = String(text);
            if (s.includes('douyin.com') || s.includes('v.douyin')) {
              send({ type: 'share-url', url: s, source: 'clipboard' });
            }
          }
          // Also log all clipboard writes for debugging
          if (text && String(text).length < 200) {
            send({ type: 'clipboard', text: String(text) });
          }
        } catch(e) {}
        return this.setPrimaryClip(clip);
      };
      send({ type: 'hooked', target: 'ClipboardManager.setPrimaryClip' });
    } catch(e) { send({ type: 'hook-fail', target: 'Clipboard', error: String(e) }); }

    // Hook share intent creation — catches android.intent.action.SEND
    try {
      const Intent = Java.use('android.content.Intent');
      Intent.setAction.implementation = function (action) {
        try {
          const act = String(action);
          if (act === 'android.intent.action.SEND') {
            const extras = this.getExtras();
            if (extras) {
              const text = extras.getString('android.intent.extra.TEXT');
              if (text && text.includes('douyin.com')) {
                send({ type: 'share-url', url: text, source: 'intent' });
              }
            }
          }
        } catch(e) {}
        return this.setAction(action);
      };
      send({ type: 'hooked', target: 'Intent.setAction (share detection)' });
    } catch(e) {}

    // Hook Html.buildShareShortUrl or similar URL shortener
    // The share link is usually a short URL generated by the server
    try {
      const TextUtils = Java.use('android.text.TextUtils');
      // Just monitor for douyin URLs in any context
    } catch(e) {}
  });
}

setTimeout(install, 2000);
send({ type: 'ready' });
